    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        try {
    
    
        String kode = txtkode.getText().trim();
        String nama = txtnama.getText().trim();
        String kategori = jComboBox1.getSelectedItem().toString();
        String teksStok = txtkategori.getText().trim();

        if (kode.isEmpty() || nama.isEmpty() || teksStok.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Semua data harus diisi!");
            return;
        }

        int stok = Integer.parseInt(teksStok);

        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

        // Periksa kode barang yang sudah ada
        for (int i = 0; i < model.getRowCount(); i++) {
            String kodeLama = model.getValueAt(i, 0).toString();

            if (kode.equalsIgnoreCase(kodeLama)) {
                JOptionPane.showMessageDialog(this,
                    "Gagal menambahkan data! Kode barang sudah tersedia!");
                return;
            }
        }

        // Tambahkan data baru
        model.addRow(new Object[]{
            kode, nama, kategori, stok
        });

        JOptionPane.showMessageDialog(this,
            "Data barang berhasil disimpan!");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
            "Stok harus berupa angka!");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Gagal menyimpan: " + e.getMessage());
    }


    }//GEN-LAST:event_btnSimpanActionPerformed

